/**
 * PipelineSpec v1 (P60-M1-002): the contract for one candidate pipeline.
 *
 * Since Revision 7 (D11) a PipelineSpec is produced by the deterministic composer, never by the
 * language model. It is also the contract the validator (P60-M1-003) and the canvas applier
 * (P60-M1-007) consume. It describes graph structure and user-facing text only: no positions,
 * node IDs, runtime state or card configuration.
 *
 * Example:
 *   {
 *     "specVersion": 1,
 *     "title": "Architecture overview",
 *     "summary": "Runs System Visualization.",
 *     "nodes": [
 *       { "key": "system_input", "cardType": "SYSTEM_INPUT" },
 *       { "key": "multi_repo", "cardType": "MULTI_REPO" },
 *       { "key": "ir_holder", "cardType": "IR_HOLDER" },
 *       { "key": "visualization", "cardType": "VISUALIZATION" }
 *     ],
 *     "edges": [
 *       { "from": "system_input", "to": "multi_repo" },
 *       { "from": "multi_repo", "to": "ir_holder" },
 *       { "from": "ir_holder", "to": "visualization" }
 *     ]
 *   }
 *
 * `parsePipelineSpec` copies only these fields, reports anything else in `ignoredFields`, and
 * never throws. Card-type membership and graph rules are the validator's job, not the parser's.
 * The intent contract (intentPlan.ts) is deliberately separate: this module does not depend on it.
 */
import { ContractIssue, cleanText, isPlainObject } from './contractIssue';

export type SpecIssue = ContractIssue;

export interface PipelineSpecNode {
    key: string;
    cardType: string;
}

export interface PipelineSpecEdge {
    from: string;
    to: string;
}

export interface PipelineSpecV1 {
    specVersion: 1;
    /** 1..60 characters. */
    title: string;
    /** 1..280 characters, plain text. Generated by the composer from capability titles. */
    summary: string;
    /** 0..400 characters, "why this fits". */
    rationale?: string;
    nodes: PipelineSpecNode[];
    edges: PipelineSpecEdge[];
}

export type ParsePipelineSpecResult =
    | { ok: true; spec: PipelineSpecV1; ignoredFields: string[] }
    | { ok: false; issues: SpecIssue[]; ignoredFields: string[] };

export const SPEC_TITLE_MAX = 60;
export const SPEC_SUMMARY_MAX = 280;
export const SPEC_RATIONALE_MAX = 400;
export const NODE_KEY_PATTERN = /^[a-z][a-z0-9_-]{0,31}$/;

const SPEC_FIELDS = ['specVersion', 'title', 'summary', 'rationale', 'nodes', 'edges'];
const NODE_FIELDS = ['key', 'cardType'];
const EDGE_FIELDS = ['from', 'to'];

const readText = (
    obj: Record<string, unknown>,
    field: string,
    max: number,
    required: boolean,
    issues: SpecIssue[]
): string | undefined => {
    const raw = obj[field];
    if (raw === undefined || raw === null) {
        if (required) issues.push({ code: `MISSING_${field.toUpperCase()}`, message: `${field} is required.`, path: field });
        return undefined;
    }
    if (typeof raw !== 'string') {
        issues.push({ code: `BAD_${field.toUpperCase()}`, message: `${field} must be a string.`, path: field });
        return undefined;
    }
    const text = cleanText(raw);
    if (text.length === 0) {
        if (required) issues.push({ code: `MISSING_${field.toUpperCase()}`, message: `${field} must not be empty.`, path: field });
        return undefined;
    }
    if (text.length > max) {
        issues.push({ code: `${field.toUpperCase()}_TOO_LONG`, message: `${field} must be at most ${max} characters.`, path: field });
        return undefined;
    }
    return text;
};

const unknownFields = (obj: Record<string, unknown>, allowed: string[], prefix: string): string[] =>
    Object.keys(obj)
        .filter((key) => !allowed.includes(key))
        .map((key) => `${prefix}${key}`);

const parseUnsafe = (raw: unknown): ParsePipelineSpecResult => {
    if (!isPlainObject(raw)) {
        return { ok: false, issues: [{ code: 'NOT_OBJECT', message: 'A PipelineSpec must be a JSON object.' }], ignoredFields: [] };
    }
    const issues: SpecIssue[] = [];
    const ignoredFields = unknownFields(raw, SPEC_FIELDS, '');

    if (raw.specVersion !== 1) {
        issues.push({ code: 'BAD_SPEC_VERSION', message: 'specVersion must be 1.', path: 'specVersion' });
    }
    const title = readText(raw, 'title', SPEC_TITLE_MAX, true, issues);
    const summary = readText(raw, 'summary', SPEC_SUMMARY_MAX, true, issues);
    const rationale = readText(raw, 'rationale', SPEC_RATIONALE_MAX, false, issues);

    const nodes: PipelineSpecNode[] = [];
    if (!Array.isArray(raw.nodes)) {
        issues.push({ code: 'NODES_NOT_ARRAY', message: 'nodes must be an array.', path: 'nodes' });
    } else {
        raw.nodes.forEach((node, i) => {
            const path = `nodes[${i}]`;
            if (!isPlainObject(node)) {
                issues.push({ code: 'BAD_NODE', message: 'Each node must be an object.', path });
                return;
            }
            ignoredFields.push(...unknownFields(node, NODE_FIELDS, `${path}.`));
            const key = typeof node.key === 'string' ? node.key : null;
            const cardType = typeof node.cardType === 'string' ? cleanText(node.cardType) : null;
            if (key === null || !NODE_KEY_PATTERN.test(key)) {
                issues.push({ code: 'BAD_NODE_KEY', message: `Node key must match ${NODE_KEY_PATTERN}.`, path: `${path}.key` });
            }
            if (!cardType) {
                issues.push({ code: 'BAD_NODE_CARD_TYPE', message: 'Node cardType must be a non-empty string.', path: `${path}.cardType` });
            }
            if (key !== null && NODE_KEY_PATTERN.test(key) && cardType) nodes.push({ key, cardType });
        });
    }

    const edges: PipelineSpecEdge[] = [];
    if (!Array.isArray(raw.edges)) {
        issues.push({ code: 'EDGES_NOT_ARRAY', message: 'edges must be an array.', path: 'edges' });
    } else {
        raw.edges.forEach((edge, i) => {
            const path = `edges[${i}]`;
            if (!isPlainObject(edge)) {
                issues.push({ code: 'BAD_EDGE', message: 'Each edge must be an object.', path });
                return;
            }
            ignoredFields.push(...unknownFields(edge, EDGE_FIELDS, `${path}.`));
            if (typeof edge.from !== 'string' || typeof edge.to !== 'string' || !edge.from || !edge.to) {
                issues.push({ code: 'BAD_EDGE_ENDPOINT', message: 'Edge from/to must be non-empty strings.', path });
                return;
            }
            edges.push({ from: edge.from, to: edge.to });
        });
    }

    if (issues.length > 0 || title === undefined || summary === undefined) {
        return { ok: false, issues, ignoredFields };
    }
    const spec: PipelineSpecV1 = { specVersion: 1, title, summary, nodes, edges };
    if (rationale !== undefined) spec.rationale = rationale;
    return { ok: true, spec, ignoredFields };
};

/** Strictly parses an untrusted value into a PipelineSpecV1. Never throws. */
export const parsePipelineSpec = (raw: unknown): ParsePipelineSpecResult => {
    try {
        return parseUnsafe(raw);
    } catch (error) {
        return {
            ok: false,
            issues: [{ code: 'PARSE_ERROR', message: `Unexpected input: ${String((error as Error)?.message ?? error)}` }],
            ignoredFields: [],
        };
    }
};
